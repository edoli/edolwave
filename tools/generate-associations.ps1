[CmdletBinding()]
param([Parameter(Mandatory)][string]$OutputFile)
$ErrorActionPreference = 'Stop'
$formats = Get-Content -LiteralPath (Join-Path $PSScriptRoot '..\installer\audio-formats.json') -Raw | ConvertFrom-Json
$extensions = @($formats.native) + @($formats.ffmpeg)
if (@($extensions | Where-Object { $_ -cnotmatch '^[a-z0-9]+$' }).Count -or
    @($extensions | Select-Object -Unique).Count -ne $extensions.Count) {
    throw 'Audio extensions must be unique lowercase names without a dot.'
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('; Generated by tools/generate-associations.ps1 from installer/audio-formats.json.')
$lines.Add('[Tasks]')
foreach ($extension in $extensions) {
    $requiresFfmpeg = $extension -in $formats.ffmpeg
    $label = if ($requiresFfmpeg) { ".$extension (requires separately installed FFmpeg)" } else { ".$extension" }
    $flags = if ($requiresFfmpeg) { '; Flags: unchecked dontinheritcheck' } else { '' }
    $lines.Add(('Name: "fileassociations\{0}"; Description: "{1}"; GroupDescription: "Audio file associations"{2}' -f $extension, $label, $flags))
}
$lines.Add('[Registry]')
foreach ($extension in $extensions) {
    $task = "fileassociations\$extension"
    # Remove only our values when an upgrade deselects a previously selected format.
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\.{0}\OpenWithProgids"; ValueType: none; ValueName: "EdolWave.Audio"; Tasks: not {1}; Flags: deletevalue' -f $extension, $task))
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\Applications\edolwave.exe\SupportedTypes"; ValueType: none; ValueName: ".{0}"; Tasks: not {1}; Flags: deletevalue' -f $extension, $task))
    $lines.Add(('Root: HKA; Subkey: "Software\Edoli\EdolWave\Capabilities\FileAssociations"; ValueType: none; ValueName: ".{0}"; Tasks: not {1}; Flags: deletevalue' -f $extension, $task))
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\.{0}\OpenWithProgids"; ValueType: string; ValueName: "EdolWave.Audio"; ValueData: ""; Tasks: {1}; Flags: uninsdeletevalue uninsdeletekeyifempty' -f $extension, $task))
    $lines.Add(('Root: HKA; Subkey: "Software\Classes\Applications\edolwave.exe\SupportedTypes"; ValueType: string; ValueName: ".{0}"; ValueData: ""; Tasks: {1}; Flags: uninsdeletevalue uninsdeletekeyifempty' -f $extension, $task))
    $lines.Add(('Root: HKA; Subkey: "Software\Edoli\EdolWave\Capabilities\FileAssociations"; ValueType: string; ValueName: ".{0}"; ValueData: "EdolWave.Audio"; Tasks: {1}; Flags: uninsdeletevalue uninsdeletekeyifempty' -f $extension, $task))
}
[IO.File]::WriteAllLines([IO.Path]::GetFullPath($OutputFile), $lines, [Text.Encoding]::UTF8)
